// Generates src/schema_snapshot.luau from Roblox-Client-Tracker's Full-API-Dump.json.
//
// The snapshot is the offline half of the schema. At runtime the saver asks the live
// client's ReflectionService first (exact for the running build) and uses this snapshot
// for the serialized members ReflectionService hides (AttributesSerialize, Tags, union
// MeshData2/PhysicsData, Script Source, ...) and as a full fallback when reflection is
// unavailable.
//
// Use the FULL dump: the Mini/API-Dump variants strip hidden members such as
// BasePart.Color3uint8 and BasePart.size, and the setup.rbxcdn.com dump is stale.
//
// usage: node tools/gen-schema.mjs [path/to/Full-API-Dump.json]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_URL = "https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/Full-API-Dump.json";
const VERSION_URL = "https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/version.txt";

// Types the XML writer knows how to encode. Anything else is left out of the snapshot.
const DATA_TYPES = new Set([
  "bool", "int", "int64", "float", "double", "string", "ProtectedString", "BinaryString",
  "SharedString", "NetAssetRef", "Content", "ContentId", "Vector2", "Vector2int16", "Vector3",
  "Vector3int16", "Color3", "Color3uint8", "BrickColor", "UDim", "UDim2", "Rect", "NumberRange",
  "NumberSequence", "ColorSequence", "PhysicalProperties", "Ray", "Faces", "Axes", "Font",
  "SecurityCapabilities", "UniqueId",
]);
const RENAMED = { CFrame: "CFrame", OptionalCoordinateFrame: "OptionalCFrame" };

function typeOf(valueType) {
  if (valueType.Category === "Enum") return "token";
  if (valueType.Category === "Class") return "Ref";
  const name = RENAMED[valueType.Name] ?? valueType.Name;
  if (name === "CFrame" || name === "OptionalCFrame" || DATA_TYPES.has(name)) return name;
  return null;
}

async function load() {
  const path = process.argv[2];
  if (path) return { json: readFileSync(path, "utf8"), version: process.argv[3] ?? "local" };
  const [json, version] = await Promise.all([
    fetch(SOURCE_URL).then((r) => r.text()),
    fetch(VERSION_URL).then((r) => r.text()),
  ]);
  return { json, version: version.trim() };
}

const { json, version } = await load();
const dump = JSON.parse(json);
const lines = [];
let propCount = 0;
const skippedTypes = new Map();

for (const cls of dump.Classes) {
  const tags = new Set((cls.Tags ?? []).filter((t) => typeof t === "string"));
  let flags = "";
  if (tags.has("NotCreatable")) flags += "N";
  if (tags.has("Service")) flags += "S";

  const props = [];
  for (const m of cls.Members) {
    if (m.MemberType !== "Property") continue;
    const ser = m.Serialization ?? {};
    if (!ser.CanSave || !ser.CanLoad) continue;
    const type = typeOf(m.ValueType);
    if (!type) {
      skippedTypes.set(m.ValueType.Name, (skippedTypes.get(m.ValueType.Name) ?? 0) + 1);
      continue;
    }
    const mtags = m.Tags ?? [];
    let pflags = mtags.includes("NotScriptable") ? "H" : "";
    const preferred = mtags.find((t) => typeof t === "object" && t?.PreferredDescriptorName);
    if (preferred) pflags += ">" + preferred.PreferredDescriptorName;
    props.push(`${m.Name}:${type}${pflags ? ":" + pflags : ""}`);
    propCount++;
  }
  const entry = `${cls.Superclass && cls.Superclass !== "<<<ROOT>>>" ? cls.Superclass : ""}|${flags}|${props.join(",")}`;
  lines.push(`\t[${JSON.stringify(cls.Name)}] = ${JSON.stringify(entry)},`);
}

const out = [
  "-- AUTO-GENERATED by tools/gen-schema.mjs from MaximumADHD/Roblox-Client-Tracker Full-API-Dump.json.",
  "-- Do not edit by hand; rerun the generator after a Roblox update.",
  "-- Format per class: \"Superclass|classFlags|name:type[:propFlags],...\"",
  "--   classFlags: N = NotCreatable, S = Service",
  "--   propFlags:  H = NotScriptable (read through gethiddenproperty), >Name = preferred scriptable alias",
  "return {",
  `\tversion = ${JSON.stringify(version)},`,
  "\tclasses = {",
  ...lines.map((l) => "\t" + l),
  "\t},",
  "}",
  "",
].join("\n");

const target = join(ROOT, "src", "schema_snapshot.luau");
writeFileSync(target, out);
console.log(`wrote ${target}: ${dump.Classes.length} classes, ${propCount} serialized properties, ${out.length} bytes`);
if (skippedTypes.size) console.log("skipped value types:", Object.fromEntries(skippedTypes));
